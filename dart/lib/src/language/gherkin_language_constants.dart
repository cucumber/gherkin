/// The character that starts a tag.
const tagPrefix = '@';

/// The character that starts a comment.
const commentPrefix = '#';

/// The character that separates a title keyword from its text.
const titleKeywordSeparator = ':';

/// The character that separates cells in a table row.
const tableCellSeparator = '|';

/// The delimiter that opens and closes a doc string.
const docStringSeparator = '"""';

/// The alternate delimiter that opens and closes a doc string.
const docStringAlternativeSeparator = '```';
